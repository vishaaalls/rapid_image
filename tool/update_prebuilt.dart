// Points the build hook at the binaries of a GitHub release.
//
//   dart run tool/update_prebuilt.dart v0.1.0
//
// Downloads SHA256SUMS from that release and rewrites lib/src/prebuilt.dart.
// Commit the result: from then on, apps get the verified prebuilt library
// and don't need Rust.

import 'dart:convert';
import 'dart:io';

import 'package:rapid_image/src/prebuilt.dart' show prebuiltBaseUrl;

Future<void> main(List<String> args) async {
  if (args.length != 1) {
    stderr.writeln('usage: dart run tool/update_prebuilt.dart <tag>');
    exit(64);
  }
  final tag = args.single;
  final url = Uri.parse('$prebuiltBaseUrl/$tag/SHA256SUMS');
  final client = HttpClient();
  final res = await (await client.getUrl(url)).close();
  if (res.statusCode != 200) {
    stderr.writeln('GET $url -> HTTP ${res.statusCode}');
    exit(1);
  }
  final sums = await res.transform(utf8.decoder).join();
  client.close();

  const libs = ['librapid_image.so', 'librapid_image.dylib', 'rapid_image.dll'];
  final entries = <String, String>{};
  for (final line in const LineSplitter().convert(sums)) {
    final parts = line.trim().split(RegExp(r'\s+\*?'));
    if (parts.length != 2) continue;
    final (hash, file) = (parts[0], parts[1]);
    final lib = libs.firstWhere((l) => file.endsWith('-$l'), orElse: () => '');
    if (lib.isEmpty) continue;
    final triple = file.substring(0, file.length - lib.length - 1);
    entries['$triple/$lib'] = hash;
  }
  if (entries.isEmpty) {
    stderr.writeln('No library entries found in $url');
    exit(1);
  }

  final sorted = entries.keys.toList()..sort();
  final out = StringBuffer('''
// Prebuilt native libraries published by .github/workflows/release.yml.
//
// GENERATED by tool/update_prebuilt.dart after a release: do not edit by hand.
// While [prebuiltVersion] is empty, the build hook always builds with cargo.

const prebuiltBaseUrl =
    'https://github.com/vishaaalls/rapid_image/releases/download';

/// Release tag holding the binaries, e.g. 'v0.1.0'.
const prebuiltVersion = '$tag';

/// '<rust triple>/<file name>' -> SHA-256 of the file.
const prebuiltHashes = <String, String>{
''');
  for (final k in sorted) {
    out.writeln("  '$k':\n      '${entries[k]}',");
  }
  out.writeln('};');
  File.fromUri(Platform.script.resolve('../lib/src/prebuilt.dart'))
      .writeAsStringSync(out.toString());
  stdout.writeln(
      'lib/src/prebuilt.dart now points at $tag (${entries.length} libraries).');
}
