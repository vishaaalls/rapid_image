#!/usr/bin/env bash
# Builds the image operations (native/src/ops.rs) for the browser and embeds
# the module in the Dart package (lib/src/wasm_bytes.g.dart), so web apps
# need no extra asset setup. The PNG encoder stays native-only: on the web
# PNG data is compressed by rapid_archive's own WebAssembly.
# Needs: rustup target add wasm32-unknown-unknown (no C toolchain: the web
# build is pure Rust). Uses wasm-opt if it's installed.
set -euo pipefail
cd "$(dirname "$0")/.."
RUSTFLAGS="-C target-feature=+simd128" \
  cargo build --release --target wasm32-unknown-unknown \
  --manifest-path native/Cargo.toml --target-dir native/target/wasm
wasm=native/target/wasm/wasm32-unknown-unknown/release/rapid_image.wasm
if command -v wasm-opt >/dev/null; then
  wasm-opt -O3 --enable-simd --enable-bulk-memory "$wasm" -o "$wasm"
fi
{
  echo "// GENERATED by tool/build_wasm.sh from native/. Do not edit."
  echo "// $(wc -c < "$wasm" | tr -d ' ') bytes of WebAssembly (wasm32 + simd128), base64-encoded."
  echo "const String rapidImageWasmBase64 ="
  base64 < "$wasm" | tr -d '\n' | fold -w 76 | sed "s/.*/    '&'/"
  echo "    ;"
} > lib/src/wasm_bytes.g.dart
echo "wrote lib/src/wasm_bytes.g.dart ($(wc -c < "$wasm" | tr -d ' ') byte wasm)"
